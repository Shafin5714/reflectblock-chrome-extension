import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const RULESET_COUNT = 6;
const projectRoot = resolve(import.meta.dirname, '..');
const sourcePath = resolve(projectRoot, 'data/adult-domains.txt');
const outputDirectory = resolve(projectRoot, 'public/rules');

const contents = await readFile(sourcePath, 'utf8');
const domains = [...new Set(
  contents
    .split(/\r?\n/)
    .map((domain) => domain.trim().toLowerCase())
    .filter((domain) => /^[a-z0-9.-]+\.[a-z]{2,}$/i.test(domain)),
)].sort();

const buckets = Array.from({ length: RULESET_COUNT }, () => []);
domains.forEach((domain, index) => buckets[index % RULESET_COUNT].push(domain));

await rm(outputDirectory, { recursive: true, force: true });
await mkdir(outputDirectory, { recursive: true });

const counts = [];
for (const [index, domainsInRuleset] of buckets.entries()) {
  const rules = domainsInRuleset.map((domain, ruleIndex) => ({
    id: ruleIndex + 1,
    priority: 1,
    action: {
      type: 'redirect',
      redirect: { extensionPath: '/blocked.html' },
    },
    condition: {
      urlFilter: `||${domain}^`,
      resourceTypes: ['main_frame'],
    },
  }));
  const fileName = `adult-${String(index + 1).padStart(2, '0')}.json`;
  await writeFile(resolve(outputDirectory, fileName), `${JSON.stringify(rules)}\n`);
  counts.push({ id: `adult_${String(index + 1).padStart(2, '0')}`, count: rules.length });
}

await writeFile(
  resolve(projectRoot, 'src/background/adult-rulesets.ts'),
  `/** Generated by scripts/build-adult-rules.mjs. */\nexport const ADULT_RULESETS = ${JSON.stringify(counts)} as const;\nexport const ADULT_DOMAIN_COUNT = ${domains.length};\n`,
);

console.log(`Generated ${domains.length} adult-domain rules across ${RULESET_COUNT} rulesets.`);
